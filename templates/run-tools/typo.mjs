/* Набор при выводе — для сайта, где страницы собираются на сервере строками, а тексты лежат в шаблонах и базе.
   copy.mjs fix --typograph правит файлы, но не то, что придёт из базы завтра; эта функция ставится в месте,
   где страница собрана целиком (вокруг <main>), и трогает только текст между тегами.

   Что делает: предлог или союз в одну-две буквы не остаётся в конце строки (неразрывный пробел после него);
   тире не уходит в начало строки; число не отрывается от единицы («25 кг», «98 ₽»); прямые кавычки →
   «ёлочки»; дефис и короткое тире между словами → тире; «Вы» и «Ваш» в середине фразы → со строчной.
   Чего не трогает: атрибуты (значения полей формы!), script, style, textarea. Слова не меняются.

   Чужой текст (статьи и описания заказчика) правится только так — набором; смысл и слова — по согласованию.

   import { typo } from './typo.mjs';   →   `<main>${typo(body)}</main>`
   node typo.mjs — самопроверка. */
const NBSP = String.fromCharCode(160);
const NOT_TEXT = /(<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<textarea[\s\S]*?<\/textarea>|<[^>]+>)/g;

export const typo = (html) => String(html || '').split(NOT_TEXT).map((part, i) => (i % 2 ? part : part
  .replace(/&quot;(?=[А-Яа-яЁёA-Za-z0-9])([^&<>]{1,90}?)(?<=[А-Яа-яЁёA-Za-z0-9.!?…])&quot;/g, '«$1»')
  .replace(/(?<=[А-Яа-яЁё»)\d.]) [-–] (?=[А-Яа-яЁё«(\d])/g, ' — ')
  .replace(/(?<=[а-яё,;:»] )В(ы|ам|ас|ами|аш|аша|аше|аши|ашего|ашей|ашему|ашим|ашими|ашу|аших)(?![А-Яа-яЁё])/g, 'в$1')
  .replace(/(?<=^|[\s(«„])([А-Яа-яЁё]{1,2}) (?=\S)/g, `$1${NBSP}`)
  .replace(/ (?=[—–] )/g, NBSP)
  .replace(/(\d) (?=(?:г|кг|т|шт|мл|л|мм|см|м|₽|%)(?![А-Яа-яЁё]))/g, `$1${NBSP}`))).join('');

if (import.meta.url === `file://${process.argv[1]?.replace(/\\/g, '/')}` || import.meta.url.endsWith(encodeURI(String(process.argv[1] || '').replace(/\\/g, '/').split('/').pop() || '\0'))) {
  const N = NBSP; let fail = 0;
  const eq = (name, got, want) => { const ok = got === want; if (!ok) fail++; console.log(`${ok ? 'OK  ' : 'FAIL'} ${name}${ok ? '' : `\n     получено: ${JSON.stringify(got)}\n     ждали:    ${JSON.stringify(want)}`}`); };
  eq('предлог не висит', typo('<p>Семена и травы в пакете</p>'), `<p>Семена и${N}травы в${N}пакете</p>`);
  eq('тире не в начале строки', typo('<p>Клевер — медонос</p>'), `<p>Клевер${N}— медонос</p>`);
  eq('число с единицей', typo('<b>25 кг</b> <i>98 ₽</i>'), `<b>25${N}кг</b> <i>98${N}₽</i>`);
  eq('кавычки', typo('<p>сорт &quot;Спортивная&quot; и &quot;Универсальная&quot;</p>'), `<p>сорт «Спортивная» и${N}«Универсальная»</p>`);
  eq('дефис между словами → тире', typo('<p>Горчица - сидерат</p>'), `<p>Горчица${N}— сидерат</p>`);
  eq('«Вы» в середине фразы', typo('<p>Если Вы выбрали товар, Вам позвонят. Вы увидите счёт</p>'), `<p>Если вы${N}выбрали товар, вам позвонят. Вы${N}увидите счёт</p>`);   // «вы» — слово в две буквы, после него тоже неразрывный
  eq('атрибуты целы', typo('<input value="в заявке - 5 кг"><a title="и так далее">ок</a>'), '<input value="в заявке - 5 кг"><a title="и так далее">ок</a>');
  eq('script и textarea целы', typo('<script>var a = "и в";</script><textarea>и в поле - так</textarea>'), '<script>var a = "и в";</script><textarea>и в поле - так</textarea>');
  eq('телефон цел', typo('<a>+7 920 367-84-29</a>'), '<a>+7 920 367-84-29</a>');
  console.log(fail ? `FAIL: провалов ${fail}` : 'OK: 9 проверок, провалов 0');
  process.exit(fail ? 1 : 0);
}
