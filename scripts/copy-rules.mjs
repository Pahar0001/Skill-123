/** Сравнимая запись заявления: без пробелов, строчными, тире → «-», ё → е, «руб.» → ₽. */
export function norm(s) {
  return String(s).toLowerCase().replace(/[\s\u00a0\u202f\u2009]+/g, '').replace(/[–—−]/g, '-').replace(/ё/g, 'е')
    .replace(/руб\p{L}*\.?|р\./gu, '₽');
}
/* подписи заявления: «вид|единица|число» для каждого числа — чтобы «1 000–20 000 ₽» сошлось с «от 1 000 до 20 000 ₽» */
function sigsOf(kind, raw) {
  const t = String(raw).toLowerCase().replace(/ё/g, 'е');
  if (kind === 'guarantee' || kind === 'rank') return [`${kind}|${norm(t).slice(0, 7)}`];
  const mult = /тыс/.test(t) ? 1000 : /млн/.test(t) ? 1e6 : 1;
  const flat = t.replace(/(\d)[\s\u00a0\u202f](?=\d{3}(?!\d))/g, '$1');
  const nums = [...flat.matchAll(/\d+(?:[.,]\d+)?/g)].map((m) => String(parseFloat(m[0].replace(',', '.')) * mult));
  /* «две недели», «двадцать минут»: самая длинная основа из WORDNUM в начале слова */
  if (!/\d/.test(t)) for (const w of t.match(/\p{L}+/gu) || []) {
    const k = Object.keys(WORDNUM).filter((x) => w.startsWith(x)).sort((a, b) => b.length - a.length)[0];
    if (k) nums.push(String(WORDNUM[k]));
  }
  let unit = '';
  if (kind === 'price') unit = /\$/.test(t) ? '$' : /€/.test(t) ? '€' : '₽';
  else if (kind === 'percent') unit = '%';
  else if (kind === 'term') unit = /мин/.test(t) ? 'мин' : /час|ч\./.test(t) ? 'час' : /дн|день|сут/.test(t) ? 'день' : /недел/.test(t) ? 'неделя' : /мес/.test(t) ? 'месяц' : 'год';
  else if (kind === 'count') unit = ((t.match(/\p{L}+/u) || [''])[0]).slice(0, 5);
  return [...new Set(nums)].map((n) => `${kind}|${unit}|${n}`);
}

/** Заявления в тексте: [{ kind, text, index, norm, sigs }] — без наложений, годы («с 2019 года») — не срок. */
export function claimsOf(text) {
  const s = String(text); const out = []; const taken = [];
  const free = (a, b) => !taken.some(([x, y]) => a < y && b > x);
  for (const { kind, re } of CLAIM_RES) {
    re.lastIndex = 0;
    for (const m of s.matchAll(re)) {
      const raw = m[0].trim(); if (raw.length < 2) continue;
      const a = m.index + m[0].indexOf(raw); const b = a + raw.length;
      if (!free(a, b)) continue;
      /* год, а не срок: «в 2024 году», «с 2019 года» */
      if (kind === 'term' && /^(?:(?:за|в течение|через|от|до)\s+)?(?:19|20)\d\d\s*(?:год|г\.)/iu.test(raw)) continue;
      taken.push([a, b]);
      out.push({ kind, text: raw, index: a, norm: norm(raw), sigs: sigsOf(kind, raw) });
    }
  }
  return out.sort((x, y) => x.index - y.index);
}

/**
 * База подтверждённого: facts — записи facts.json ({ fact, source, what }); texts — тексты сайта «до».
 * → { text: нормализованный текст всех источников, sigs: Set, facts: n, texts: n, empty, noSource: [записи без source] }.
 * Запись без source в базу не входит: факт без источника — не факт (copy.mjs даёт по ней FAIL).
 */
export function factIndex({ facts = [], texts = [] } = {}) {
  const parts = []; const sigs = new Set(); const noSource = []; let n = 0; let nt = 0;
  for (const f of facts || []) {
    const fact = f && typeof f === 'object' ? String(f.fact ?? '') : String(f ?? '');
    if (!fact.trim()) continue;
    if (!f || typeof f !== 'object' || !String(f.source ?? '').trim()) { noSource.push(fact); continue; }
    n++; parts.push(norm(fact)); for (const c of claimsOf(fact)) for (const g of c.sigs) sigs.add(g);
  }
  for (const t of texts || []) { const s = String(t ?? ''); if (!s.trim()) continue; nt++; parts.push(norm(s)); for (const c of claimsOf(s)) for (const g of c.sigs) sigs.add(g); }
  return { text: parts.join('\u0001'), sigs, facts: n, texts: nt, empty: !n && !nt, noSource };
}
/* вхождение нормализованного заявления в базу — не внутри другого числа: «500₽» не находится в «1500₽» */
function inText(text, needle) {
  if (!needle) return false;
  for (let i = text.indexOf(needle); i >= 0; i = text.indexOf(needle, i + 1)) {
    const p = text[i - 1] || ''; const pp = text[i - 2] || '';
    const numStart = /\d/.test(needle[0]);
    if (numStart && (/\d/.test(p) || (/[.,]/.test(p) && /\d/.test(pp)))) continue;
    const q = text[i + needle.length] || '';
    if (/\d$/.test(needle) && /\d/.test(q)) continue;
    return true;
  }
  return false;
}
export const confirmed = (idx, c) => !!idx && (inText(idx.text, c.norm) || (c.sigs.length > 0 && c.sigs.every((g) => idx.sigs.has(g))));

