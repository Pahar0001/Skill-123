/** Предложения с отрезками [a, b) в строке s (s уже без лишних пробелов). */
export function sentencesAt(s) {
  const out = []; let start = 0;
  const re = /([.!?…]+[»")\]]*)\s+(?=[«"„(]?[\p{Lu}\d—–])/gu; let m;
  while ((m = re.exec(s))) {
    const end = m.index + m[1].length;
    /* «ул. Свободы», «г. Рыбинск», инициалы «А. С.» — не конец предложения */
    if (m[1] === '.') { const w = (/([\p{L}]+)$/u.exec(s.slice(Math.max(0, m.index - 12), m.index)) || [])[1] || ''; if (ABBR.has(w.toLowerCase()) || /^\p{Lu}$/u.test(w)) continue; }
    const t = s.slice(start, end).trim(); if (t) out.push({ s: t, a: start, b: end });
    start = end;
  }
  const t = s.slice(start).trim(); if (t) out.push({ s: t, a: start, b: s.length });
  return out;
}
