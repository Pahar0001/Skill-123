/** copy.allow.json → { brand, words, phrases, rules: { правило: [фразы] }, off: Set, templates: [имена] }. */
export function allowOf(a) {
  const arr = (v) => (Array.isArray(v) ? v.map(String).filter(Boolean) : []);
  const rules = {}; if (a && a.rules && typeof a.rules === 'object') for (const [k, v] of Object.entries(a.rules)) rules[k] = arr(v);
  const templates = a && Array.isArray(a.templates) ? arr(a.templates) : ['V'];
  return { brand: arr(a && a.brand), words: arr(a && a.words), phrases: arr(a && a.phrases), rules, off: new Set(arr(a && a.off)), templates };
}
function allowed(A, rule, match, quote) {
  const lm = match.toLowerCase(); const lq = quote.toLowerCase();
  const list = [...A.phrases, ...(rule === 'copy-self-name' ? [] : A.brand), ...(A.rules[rule] || [])];
  for (const p of list) { const lp = p.toLowerCase(); if (lp && lq.includes(lp) && (lp.includes(lm) || lm.includes(lp))) return true; }
  return !!lm && A.words.some((w) => lm.includes(w.toLowerCase()));
}

